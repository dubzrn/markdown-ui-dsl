#!/usr/bin/env node
// NOV-04 constraint evaluation (T-079): recall on seeded violations, false positives on the clean set. Writes evals/NOV-04.md.
//   node scripts/eval-nov04.mjs [--check]     (--check fails below recall 95% or with any false positive)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { lint } from "../packages/lint/dist/index.js";

const root = new URL("../evals/nov04/", import.meta.url);
const files = (d) =>
  readdirSync(new URL(d, root))
    .filter((f) => f.endsWith(".ui.md"))
    .sort();
const isConstraint = (c) => /^[EW]53\d\d$/.test(c);
const rows = [];
let hit = 0;
const violations = files("violations/");
for (const f of violations) {
  const src = readFileSync(new URL(`violations/${f}`, root), "utf8");
  const expect = /<!-- expect: (\w+) -->/.exec(src)?.[1];
  const codes = lint(src).diagnostics.map((d) => d.code);
  const ok = codes.includes(expect);
  if (ok) hit++;
  rows.push(
    `| ${f.replace(".ui.md", "")} | ${expect} | ${ok ? "found" : "**MISSED** (" + codes.filter(isConstraint).join(", ") + ")"} |`,
  );
}
const clean = files("clean/");
const falsePos = [];
for (const f of clean) {
  const codes = lint(readFileSync(new URL(`clean/${f}`, root), "utf8"))
    .diagnostics.map((d) => d.code)
    .filter(isConstraint);
  if (codes.length > 0) falsePos.push(`${f}: ${codes.join(", ")}`);
}
const recall = hit / violations.length;
const md = `# NOV-04 constraint evaluation

Generated by \`node scripts/eval-nov04.mjs\`. Fixtures: \`evals/nov04/violations\` (each declares the code it must raise) and \`evals/nov04/clean\`.

| Metric | Result | Target |
|---|---|---|
| Seeded violations found | ${hit} / ${violations.length} (**recall ${(recall * 100).toFixed(1)}%**) | >= 95% |
| False positives on the clean set | ${falsePos.length} of ${clean.length} specs | 0 |

Thresholds are configurable defaults, not universal usability truth. The fixtures are small hand-written specs, one construct per rule: they show each rule fires and stays silent where it should, not how it behaves on arbitrary real-world screens.

${falsePos.length > 0 ? "False positives:\n" + falsePos.map((x) => `- ${x}`).join("\n") + "\n\n" : ""}| Violation fixture | Expected | Result |
|---|---|---|
${rows.join("\n")}
`;
writeFileSync(new URL("../NOV-04.md", root), md);
console.log(
  `recall ${hit}/${violations.length}, false positives ${falsePos.length}/${clean.length}`,
);
for (const r of rows.filter((r) => r.includes("MISSED"))) console.log(r);
for (const x of falsePos) console.log("FP", x);
if (process.argv.includes("--check") && (recall < 0.95 || falsePos.length > 0)) process.exit(1);
