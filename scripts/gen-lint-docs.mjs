// Generates docs/LINT_RULES.md from the rule metadata. `--check` fails when the committed file is stale.
import fs from "node:fs";
import { ALL_RULES } from "../packages/lint/dist/index.js";
import { CODES } from "../packages/core/dist/index.js";

const rows = ALL_RULES.map((r) => {
  const codes = r.codes.map((c) => `\`${c}\``).join(", ");
  const wcag =
    r.wcag === undefined
      ? "—"
      : r.wcag.length === 0
        ? "best practice"
        : r.wcag.map((c) => `SC ${c}`).join(", ");
  return `| \`${r.id}\` | ${r.category} | ${r.defaultSeverity} | ${codes} | ${wcag} | ${r.fixable === true ? "yes" : ""} | ${r.description.replace(/\|/g, "\\|")} |`;
});
const codeRows = Object.entries(CODES).map(
  ([c, i]) => `| \`${c}\` | ${i.severity} | ${i.summary.replace(/\|/g, "\\|")} |`,
);
const out = `# Lint rules and diagnostic codes

_Generated by \`scripts/gen-lint-docs.mjs\` — do not edit. \`pnpm lint:docs\` regenerates, CI checks it is current._

${ALL_RULES.length} rules. Configure in \`mdui.config.json\` (\`"rules": { "<id>": "off|info|warn|error" }\`); silence one node with
\`<!-- mdui-disable <id> -->\` on the line above it (rule list optional; unused suppressions are reported as \`I1501\`).

| Rule | Category | Default | Codes | WCAG 2.2 | Fixable | What it checks |
|---|---|---|---|---|---|---|
${rows.join("\n")}

## WCAG mapping — status

"SC x.y.z" entries are the success criteria that **axe-core's own rule tags confirm** for the equivalent axe rule
(\`reference/verification/axe-core/lib/rules/*.json\`: image-alt → 1.1.1, label/button-name → 4.1.2, link-name → 2.4.4 + 4.1.2,
th-has-data-cells → 1.3.1, target-size → 2.5.8, html-has-lang → 3.1.1). Rules marked "best practice" correspond to axe
\`best-practice\` rules (heading-order, page-has-heading-one, empty-heading, landmark-unique) or have no WCAG criterion of their own.
The canonical W3C text (<https://www.w3.org/TR/WCAG22/>) could not be reached from the build environment (HTTP 403), so the
mapping must be reviewed against it before a public release (task T-032 / T-093).

## Diagnostic code registry

Ranges: 1xxx syntax · 2xxx semantic/resolution · 3xxx accessibility · 4xxx tokens · 5xxx constraints/flows. The first letter is the
severity (E error, W warning, I info).

| Code | Severity | Meaning |
|---|---|---|
${codeRows.join("\n")}
`;
const file = new URL("../docs/LINT_RULES.md", import.meta.url);
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== out) {
    console.error("docs/LINT_RULES.md is stale: run pnpm lint:docs");
    process.exit(1);
  }
  console.log("lint docs up to date");
} else fs.writeFileSync(file, out);
